#!/bin/sh
# 23a — Install Fish + fetch ALL config files from unix repo (raw GitHub)
set -eu

SUDO="sudo"
[ "$(id -u)" = "0" ] && SUDO=""
FISH_DIR="${HOME}/.config/fish"
STARSHIP_DIR="${HOME}/.config"

# Source of truth: unix repo fish asset files
RAW="https://raw.githubusercontent.com/diegonmarcos/unix/main/ba_flakes_desktop/src/modules/programs/shells/fish"

echo "=== Fish Shell Setup ==="

# ── Step 1: Install Fish ─────────────────────────────────────────
if command -v fish >/dev/null 2>&1; then
    echo "[OK] Fish installed: $(fish --version 2>/dev/null)"
else
    echo "[+] Installing Fish..."
    if command -v dnf >/dev/null 2>&1; then $SUDO dnf install -y fish
    elif command -v apt-get >/dev/null 2>&1; then $SUDO apt-get update -qq && $SUDO apt-get install -y -qq fish
    elif command -v pacman >/dev/null 2>&1; then $SUDO pacman -S --noconfirm fish
    elif command -v apk >/dev/null 2>&1; then $SUDO apk add fish
    elif command -v nix-env >/dev/null 2>&1; then nix-env -iA nixpkgs.fish
    else echo "[!] No package manager — install fish manually"; fi
fi

# ── Step 2: Set as default shell ─────────────────────────────────
if command -v fish >/dev/null 2>&1; then
    FISH_PATH=$(command -v fish)
    grep -q "$FISH_PATH" /etc/shells 2>/dev/null || echo "$FISH_PATH" | $SUDO tee -a /etc/shells >/dev/null 2>&1 || true
    CURRENT_SHELL=$(getent passwd "$(whoami)" 2>/dev/null | cut -d: -f7 || echo "")
    [ "$CURRENT_SHELL" != "$FISH_PATH" ] && $SUDO chsh -s "$FISH_PATH" "$(whoami)" 2>/dev/null && echo "[+] Default shell: fish" || true
fi

# ── Step 3: Skip if HM-managed ───────────────────────────────────
if [ -L "$FISH_DIR/config.fish" ] || ! mkdir -p "$FISH_DIR" 2>/dev/null || ! touch "$FISH_DIR/.test" 2>/dev/null; then
    echo "[OK] Fish config managed by home-manager — skipping"
    exit 0
fi
rm -f "$FISH_DIR/.test"

# ── Step 4: Fetch ALL config files from unix repo ────────────────
mkdir -p "$FISH_DIR/functions" "$FISH_DIR/conf.d" "$FISH_DIR/completions"

echo "[+] Fetching config files from unix repo (raw GitHub)..."

# interactiveShellInit → config.fish (wraps in if status is-interactive)
_init_tmp=$(mktemp)
if curl -sfL "$RAW/interactiveShellInit.fish" -o "$_init_tmp" 2>/dev/null && [ -s "$_init_tmp" ]; then
    {
        echo "# Generated by dtk.sh 23a from unix repo fish assets"
        echo "if status is-interactive"
        sed 's/^/    /' "$_init_tmp"
        echo "end"
    } > "$FISH_DIR/config.fish"
    echo "[OK] config.fish (from interactiveShellInit.fish)"
else
    echo "[!] interactiveShellInit.fish not found — generating fallback"
    cat > "$FISH_DIR/config.fish" << 'FISHCONF'
# Generated by dtk.sh 23a (fallback)
if status is-interactive
    alias ls="eza --color=auto --icons 2>/dev/null || command ls --color=auto"
    alias ll="eza -alF --icons 2>/dev/null || command ls -alF"
    alias la="eza -A --icons 2>/dev/null || command ls -A"
    alias lt="eza --tree --level=2 --icons 2>/dev/null || tree -L 2"
    alias cat="bat --paging=never 2>/dev/null || command cat"
    alias grep="rg 2>/dev/null || command grep --color=auto"
    alias find="fd 2>/dev/null || command find"
    alias ..="cd .."; alias ...="cd ../.."; alias ....="cd ../../.."
    alias rm="rm -i"; alias cp="cp -i"; alias mv="mv -i"
    alias df="duf 2>/dev/null || command df -h"
    alias du="ncdu 2>/dev/null || command du -sh"
    alias free="free -h"; alias ports="ss -tulanp"; alias myip="curl -s ifconfig.me"
    alias py="python3"; alias c="clear"; alias h="history"
    alias reload="source ~/.config/fish/config.fish"
    alias dtk="bash ~/git/tools/dtk.sh"
    abbr -a gs "git status -sb"; abbr -a ga "git add"; abbr -a gaa "git add --all"
    abbr -a gc "git commit"; abbr -a gcm "git commit -m"
    abbr -a gp "git push"; abbr -a gpl "git pull"
    abbr -a gl "git log --oneline --graph --decorate -20"
    abbr -a gd "git diff"; abbr -a gco "git checkout"
    abbr -a dps "docker ps"; abbr -a dpsa "docker ps -a"
    abbr -a dcu "docker compose up"; abbr -a dcd "docker compose down"
    fish_add_path -m ~/.cargo/bin ~/.npm-global/bin ~/go/bin ~/.local/bin ~/.nix-profile/bin
    if command -q starship; starship init fish | source; end
    if command -q zoxide; zoxide init fish | source; end
end
FISHCONF
fi
rm -f "$_init_tmp"

# Fish functions — fetch each from unix repo asset files
FUNCS_URL="$RAW/functions"
for fn in fish_greeting ai-cli cloud-ai-cli gacp gcam gpsh git_current_branch \
          extract mkcd mkd serve hhelp myhelp localip duh backup cpucap qfind \
          hg fish-e fish-e-stop __fzf_search_commands; do
    curl -sfL "$FUNCS_URL/${fn}.fish" -o "$FISH_DIR/functions/${fn}.fish" 2>/dev/null \
        && echo "[OK] functions/${fn}.fish" \
        || echo "[!] functions/${fn}.fish not found"
done

# ── Step 5: Starship config ──────────────────────────────────────
echo "[+] Writing starship.toml..."
mkdir -p "$STARSHIP_DIR"
cat > "$STARSHIP_DIR/starship.toml" << 'STAR'
format = "$username$hostname$directory$git_branch$git_status$cmd_duration$line_break$character"
[character]
success_symbol = "[>](green)"
error_symbol = "[>](red)"
[directory]
truncation_length = 3
[git_branch]
format = "[$branch]($style) "
[cmd_duration]
min_time = 2000
STAR
echo "[OK] starship.toml"

echo ""
echo "=== Done ==="
echo "Files deployed:"
echo "  ~/.config/fish/config.fish"
echo "  ~/.config/fish/functions/ ($(ls "$FISH_DIR/functions/" 2>/dev/null | wc -l) files)"
echo "  ~/.config/starship.toml"
echo ""
echo "Run: source ~/.config/fish/config.fish"
